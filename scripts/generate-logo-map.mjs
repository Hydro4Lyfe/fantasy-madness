#!/usr/bin/env node
/**
 * Fetches all NCAA men's basketball teams from ESPN API and generates
 * a TypeScript map from normalized team name → ESPN CDN logo URL.
 *
 * Usage: node scripts/generate-logo-map.mjs
 */

const ESPN_ENDPOINT =
  "https://site.api.espn.com/apis/site/v2/sports/basketball/mens-college-basketball/teams?limit=500&page=";

function normalize(name) {
  return name
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

async function fetchAllTeams() {
  const allTeams = [];
  let page = 1;
  let hasMore = true;

  while (hasMore) {
    const res = await fetch(`${ESPN_ENDPOINT}${page}`);
    if (!res.ok) throw new Error(`ESPN API ${res.status}`);
    const data = await res.json();

    const sports = data.sports ?? [];
    const leagues = sports[0]?.leagues ?? [];
    const teams = leagues[0]?.teams ?? [];

    if (teams.length === 0) {
      hasMore = false;
      break;
    }

    for (const item of teams) {
      const team = item.team;
      if (!team) continue;

      const logos = team.logos ?? [];
      const logoUrl = logos[0]?.href ?? null;
      if (!logoUrl) continue;

      allTeams.push({
        displayName: team.displayName,
        shortDisplayName: team.shortDisplayName,
        abbreviation: team.abbreviation,
        location: team.location,
        name: team.name,
        logoUrl,
      });
    }

    page++;
    // ESPN typically returns all in one page with limit=500, but just in case
    if (teams.length < 50) hasMore = false;
  }

  return allTeams;
}

async function main() {
  console.log("Fetching ESPN teams...");
  const teams = await fetchAllTeams();
  console.log(`Fetched ${teams.length} teams`);

  // Build map entries: normalized displayName → logo URL
  // Also add entries for location+name combo and just location
  const entries = new Map();

  for (const team of teams) {
    const key = normalize(team.displayName);
    if (key && !entries.has(key)) {
      entries.set(key, team.logoUrl);
    }

    // Also map "location name" combo (e.g., "Duke Blue Devils")
    if (team.location && team.name) {
      const combo = normalize(`${team.location} ${team.name}`);
      if (combo && !entries.has(combo)) {
        entries.set(combo, team.logoUrl);
      }
    }

    // Map abbreviation
    if (team.abbreviation) {
      const abbrKey = `abbr:${team.abbreviation.toLowerCase()}`;
      if (!entries.has(abbrKey)) {
        entries.set(abbrKey, team.logoUrl);
      }
    }

    // Map just the location (e.g., "Duke", "Kentucky")
    if (team.location) {
      const locKey = normalize(team.location);
      // Only add if unique - skip if we already have a different team for this location
      if (!entries.has(locKey)) {
        entries.set(locKey, team.logoUrl);
      }
    }
  }

  // Generate TypeScript map
  const sorted = [...entries.entries()].sort((a, b) => a[0].localeCompare(b[0]));

  let ts = `// Auto-generated by scripts/generate-logo-map.mjs — do not edit manually\n`;
  ts += `// Maps normalized team names to ESPN CDN logo URLs\n`;
  ts += `// Generated: ${new Date().toISOString()}\n\n`;
  ts += `export const ESPN_LOGO_MAP: Record<string, string> = {\n`;

  for (const [key, url] of sorted) {
    ts += `  ${JSON.stringify(key)}: ${JSON.stringify(url)},\n`;
  }

  ts += `};\n`;

  // Write to the web app's lib directory
  const fs = await import("node:fs/promises");
  const path = await import("node:path");
  const outPath = path.resolve(
    new URL("../apps/web/lib/espn-logo-map.ts", import.meta.url).pathname
  );

  await fs.writeFile(outPath, ts, "utf-8");
  console.log(`Written ${sorted.length} entries to ${outPath}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
